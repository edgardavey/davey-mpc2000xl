"""Generate the MPC2000XL artwork and native input layout.

This regenerates only standalone artwork/Lua files, never MAME or firmware.
"""
from pathlib import Path
import xml.etree.ElementTree as ET
from hardware_panel import WIDTH, HEIGHT, LCD, FADER, FADER_CAP, FADER_VALUE, LEDS, make_artwork

HERE = Path(__file__).resolve().parent
DEST = HERE.parent / 'artwork/mpc2000xldiag'
buttons = make_artwork(DEST)
layout = ET.Element('mamelayout', version='2')


def bounds(parent, x, y, w, h):
    ET.SubElement(parent, 'bounds', x=str(x), y=str(y), width=str(w), height=str(h))


def svg_element(name, filename, size, states=False):
    element = ET.SubElement(layout, 'element', name=name, defstate='0')
    for state in range(2) if states else [None]:
        attrs = {'file': filename.format(state=state)}
        if state is not None:
            attrs['state'] = str(state)
        component = ET.SubElement(element, 'image', attrs)
        bounds(component, 0, 0, *size)
    return element


svg_element('panel', 'panel.svg', (WIDTH, HEIGHT))
for style in sorted({button[5] for button in buttons}):
    svg_element(style, style+'-{state}.svg', (1, 1), states=True)
svg_element('variation_track', 'fader-track.svg', (1, 1))
svg_element('variation_cap', 'fader-cap.svg', (1, 1))
readout = ET.SubElement(layout, 'element', name='variation_value', defstate='0')
for value in range(128):
    label = ET.SubElement(readout, 'text', string=f'{value:03}', state=str(value))
    bounds(label, 0, 0, 1, 1)
    ET.SubElement(label, 'color', red='.27', green='.33', blue='.23')

led = ET.SubElement(layout, 'element', name='guest_led', defstate='0')
for state, rgb in [(0, (0.20, 0.24, 0.19)), (1, (0.92, 0.22, 0.12))]:
    dot = ET.SubElement(led, 'disk', state=str(state))
    bounds(dot, 0, 0, 1, 1)
    ET.SubElement(dot, 'color', red=str(rgb[0]), green=str(rgb[1]), blue=str(rgb[2]))

view = ET.SubElement(layout, 'view', name='MPC2000XL panel', showpointers='yes')
bounds(view, 0, 0, WIDTH, HEIGHT)
bounds(ET.SubElement(view, 'element', ref='panel'), 0, 0, WIDTH, HEIGHT)
bounds(ET.SubElement(view, 'screen', index='0'), *LCD)
for name, port, mask, box, output, style in buttons:
    attrs = dict(ref=style, id='key_'+name)
    if output:
        attrs['name'] = output
    bounds(ET.SubElement(view, 'element', attrs), *box)
for name, box in [('variation_track', FADER), ('variation_cap', FADER_CAP), ('variation_value', FADER_VALUE)]:
    bounds(ET.SubElement(view, 'element', ref=name, id='variation_area' if name=='variation_track' else name), *box)

for name, x, y in LEDS:
    bounds(ET.SubElement(view, 'element', ref='guest_led', name='led_'+name), x, y, 8, 8)

control_rows = '\n'.join(f'    {{"{name}", ":{port}", {mask}}},'
                         for name, port, mask, box, output, style in buttons)
pointer_script = '''
-- Generated by make_panel_layout.py. Inputs only; no guest memory writes.
do
    local view = manager.machine.render.ui_target.current_view
    local controls, active, pointers, fader_pointers = {}, {}, {}, {}
    local latchable = {rec=true, overdub=true, erase=true, tap=true, ["goto"]=true}
    local variation = manager.machine.ioport.ports[":VARIATION"].fields["NOTE VARIATION"]
    local input = manager.machine.input
    local fader_keys = {}
    for _, name in ipairs({"OPENBRACE", "CLOSEBRACE", "LCONTROL", "RCONTROL", "L"}) do
        fader_keys[name] = input:code_from_token("KEYCODE_" .. name)
    end
    local function held(name) return input:code_pressed(fader_keys[name]) end
    local fader_direction, fader_repeat = 0, 0
    view.items["variation_value"]:set_element_state_callback(function()
        return math.floor((variation.user_value * 127 + 50) / 100)
    end)
    local fader_area, fader_cap = view.items["variation_area"], view.items["variation_cap"]
    fader_cap:set_bounds_callback(function()
        local b = fader_area.bounds
        local height = b.height * 26 / 170
        local top = b.y0 + (1 - variation.user_value / 100) * (b.height - height)
        return emu.render_bounds(b.x0 + b.width * 10 / 80, top,
                                 b.x1 - b.width * 10 / 80, top + height)
    end)
    local function move_fader(y)
        local b = fader_area.bounds
        local half_cap = b.height * 13 / 170
        local ratio = 1 - (y - b.y0 - half_cap) / (b.height - 2 * half_cap)
        variation.user_value = math.floor(math.max(0, math.min(1, ratio)) * 100 + 0.5)
    end
    for _, spec in ipairs({
''' + control_rows + '''
    }) do
        local field
        for _, candidate in pairs(manager.machine.ioport.ports[spec[2]].fields) do
            if candidate.mask == spec[3] then field = candidate; break end
        end
        assert(field, "Missing panel input " .. spec[1])
        local item, port, mask = view.items["key_" .. spec[1]], manager.machine.ioport.ports[spec[2]], spec[3]
        if spec[1] ~= "shift" then
            item:set_element_state_callback(function() return (port:read() & mask) ~= 0 and 1 or 0 end)
        end
        controls[#controls + 1] = {item=item, field=field, latchable=latchable[spec[1]]}
    end
    local function release(id)
        local control = pointers[id]
        if control and active[control] then active[control].held[id] = nil end
        pointers[id], fader_pointers[id] = nil, nil
    end
    view:set_pointer_updated_callback(function(kind, id, device, x, y, buttons, pressed, released, clicks)
        -- Update the final drag coordinate before handling button release.
        if fader_pointers[id] then move_fader(y) end
        if (released & 1) ~= 0 then release(id) end
        if (pressed & 1) ~= 0 then
            release(id)
            if fader_area.bounds:includes(x, y) then
                fader_pointers[id] = true
                move_fader(y)
                return
            end
        end
        if (pressed & 3) ~= 0 then
            for _, control in ipairs(controls) do
                if control.item.bounds:includes(x, y) then
                    if (pressed & 2) ~= 0 and not control.latchable then return end
                    local state = active[control] or {frames=4, held={}, latched=false}
                    state.frames = 4
                    if (pressed & 2) ~= 0 then
                        state.latched = not state.latched
                    else
                        state.held[id], pointers[id] = true, control
                    end
                    active[control] = state
                    if state.latched or next(state.held) then control.field:set_value(1) end
                    break
                end
            end
        end
    end)
    view:set_pointer_left_callback(function(kind, id) release(id) end)
    view:set_pointer_aborted_callback(function(kind, id) release(id) end)
    view:set_forget_pointers_callback(function()
        for control in pairs(active) do control.field:clear_value() end
        active, pointers, fader_pointers = {}, {}, {}
    end)
    -- Minimum 50 ms pulses preserve down/up received in one video frame.
    mpc2000xl_panel_pointer_frames = emu.add_machine_frame_notifier(function()
        -- Same adjuster as the mouse: the driver sends 86 vv to the guest.
        -- Hold a bracket to repeat; Control jumps to an endpoint; L centres.
        local direction = (held("CLOSEBRACE") and 1 or 0) - (held("OPENBRACE") and 1 or 0)
        if not manager.ui.menu_active then
            if held("L") then
                variation.user_value = 50
            elseif direction ~= 0 then
                if held("LCONTROL") or held("RCONTROL") then
                    variation.user_value = direction > 0 and 100 or 0
                elseif direction ~= fader_direction or fader_repeat == 0 then
                    variation.user_value = math.max(0, math.min(100, variation.user_value + direction))
                end
            end
        end
        if direction == 0 then fader_repeat = 0
        elseif direction ~= fader_direction then fader_repeat = 16
        elseif fader_repeat > 0 then fader_repeat = fader_repeat - 1
        else fader_repeat = 3 end
        fader_direction = direction
        for control, state in pairs(active) do
            if state.frames > 0 or state.latched or next(state.held) then
                control.field:set_value(1)
                state.frames = math.max(0, state.frames - 1)
            else
                control.field:clear_value()
                active[control] = nil
            end
        end
    end)
end
'''

ET.indent(layout, space='  ')
dest = DEST / 'default.lay'
dest.parent.mkdir(parents=True, exist_ok=True)
ET.ElementTree(layout).write(dest, encoding='utf-8', xml_declaration=True)
(Path(__file__).resolve().parent / 'panel_input.lua').write_text(pointer_script)
print(dest)
